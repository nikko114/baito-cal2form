test('2027年の祝日', () => {
  assert.deepEqual(
    [...holidaysOf(2027)].map(([ymd]) => ymd),
    [
      '2027-01-01',
      '2027-01-11',
      '2027-02-11',
      '2027-02-23',
      '2027-03-21',
      '2027-03-22', // 春分の日が日曜なので振替休日
      '2027-04-29',
      '2027-05-03',
      '2027-05-04',
      '2027-05-05',
      '2027-07-19',
      '2027-08-11',
      '2027-09-20',
      '2027-09-23',
      '2027-10-11',
      '2027-11-03',
      '2027-11-23',
    ],
  );
  assert.equal(holidayName('2027-03-22'), '振替休日');
});

test('祝日の名前を引く', () => {
  assert.equal(holidayName('2026-11-03'), '文化の日');
  assert.equal(holidayName('2026-11-04'), null);
  assert.equal(holidayName('2026-12-25'), null);
});

test('日付を日単位でずらす（月・年をまたぐ）', () => {
  assert.equal(addDays('2026-11-30', 1), '2026-12-01');
  assert.equal(addDays('2026-12-31', 1), '2027-01-01');
  assert.equal(addDays('2027-03-01', -1), '2027-02-28');
  assert.equal(addDays('2028-02-28', 1), '2028-02-29');
});
